import { spawnSync } from "node:child_process";
import {
  cpSync,
  mkdtempSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { basename, join, relative, resolve } from "node:path";

const repoRoot = process.cwd();
const committedOutput = resolve(repoRoot, "src/contracts/generated");
const checkOnly = process.argv.includes("--check");
const temporaryRoot = mkdtempSync(join(tmpdir(), "kmark-contracts-"));
const output = join(temporaryRoot, "generated");

mkdirSync(output, { recursive: true });

const result = spawnSync(
  "cargo",
  [
    "test",
    "--manifest-path",
    "crates/kmark-contract/Cargo.toml",
    "--features",
    "bindings",
    "export_bindings",
  ],
  {
    cwd: repoRoot,
    env: {
      ...process.env,
      TS_RS_EXPORT_DIR: output,
      TS_RS_LARGE_INT: "number",
    },
    shell: process.platform === "win32",
    stdio: "inherit",
  },
);

if ((result.status ?? 1) !== 0) {
  rmSync(temporaryRoot, { force: true, recursive: true });
  process.exit(result.status ?? 1);
}

const generatedFiles = readdirSync(output)
  .filter((fileName) => fileName.endsWith(".ts") && fileName !== "index.ts")
  .sort();
const exports = generatedFiles
  .map((fileName) => {
    const typeName = basename(fileName, ".ts");
    return `export type { ${typeName} } from "./${typeName}";`;
  })
  .join("\n");
writeFileSync(join(output, "index.ts"), `// Generated by tools/generate-contracts.mjs.\n${exports}\n`);

function collectFiles(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const path = join(directory, entry.name);
      return entry.isDirectory() ? collectFiles(path) : [path];
    })
    .sort();
}

if (checkOnly) {
  const expected = collectFiles(output).map((path) => relative(output, path));
  const actual = collectFiles(committedOutput).map((path) => relative(committedOutput, path));

  if (JSON.stringify(expected) !== JSON.stringify(actual)) {
    throw new Error("Generated contract file set is stale. Run pnpm generate:contracts.");
  }

  for (const relativePath of expected) {
    const generated = readFileSync(join(output, relativePath), "utf8");
    const committed = readFileSync(join(committedOutput, relativePath), "utf8");
    if (generated !== committed) {
      throw new Error(`Generated contract is stale: ${relativePath}`);
    }
  }
} else {
  rmSync(committedOutput, { force: true, recursive: true });
  cpSync(output, committedOutput, { recursive: true });
}

rmSync(temporaryRoot, { force: true, recursive: true });
